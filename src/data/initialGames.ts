// Generate 500 sequential codes for each game (001, 002, 003... up to 500 for large festival scale)
export function generateInitialSequentialCodes(): Code[] {
  const codes: Code[] = [];
  const now = new Date().toISOString();

  for (const game of INITIAL_GAMES) {
    const prefix = game.codePrefix || 'GAME';
    for (let i = 1; i <= 500; i++) {
      const numStr = String(i).padStart(3, '0');
      codes.push({
        id: `c-${game.id}-${i}`,
        code: `${prefix}-${numStr}`,
        gameId: game.id,
        sequenceNumber: i,
        status: 'active',
        createdAt: now
      });
    }
  }

  return codes;
}

